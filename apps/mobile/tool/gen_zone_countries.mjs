// Generates lib/settings/zone_countries.dart: the country of each IANA time zone (the tz database's
// zone.tab) and the countries' names in Spanish and English (CLDR, through Node's Intl.DisplayNames).
//
// The web finds a zone by its country because Chrome's `Intl` names a zone after the country in its
// "generic name" ("hora de Colombia"); Dart's Intl has no such names, so the same search reads this
// table instead (apps/web/app/features/settings/settings-model.ts, `zoneSearchIndex`).
//
//   node tool/gen_zone_countries.mjs [/usr/share/zoneinfo/zone.tab] > lib/settings/zone_countries.dart
import { readFileSync } from "node:fs";

const source = process.argv[2] ?? "/usr/share/zoneinfo/zone.tab";
const rows = readFileSync(source, "utf8")
  .split("\n")
  .filter((line) => line && !line.startsWith("#"))
  .map((line) => line.split("\t"))
  .map(([country, , zone]) => [zone, country])
  .sort(([a], [b]) => (a < b ? -1 : 1));
const codes = [...new Set(rows.map(([, country]) => country))].sort();
const es = new Intl.DisplayNames(["es"], { type: "region" });
const en = new Intl.DisplayNames(["en"], { type: "region" });
const quote = (text) => `'${text.replaceAll("\\", "\\\\").replaceAll("'", "\\'")}'`;

const out = [];
out.push("// GENERATED by tool/gen_zone_countries.mjs: do not edit by hand.");
out.push(`// Zones and their countries: the tz database's zone.tab (${rows.length} zones). Names: CLDR.`);
out.push("");
out.push("/// The country (ISO 3166 alpha-2) of each time zone the picker lists.");
out.push("const zoneCountries = <String, String>{");
for (const [zone, country] of rows) out.push(`  ${quote(zone)}: ${quote(country)},`);
out.push("};");
out.push("");
out.push("/// A country's name in Spanish and in English.");
out.push("const countryNames = <String, (String, String)>{");
for (const code of codes) out.push(`  ${quote(code)}: (${quote(es.of(code))}, ${quote(en.of(code))}),`);
out.push("};");
console.log(out.join("\n"));
