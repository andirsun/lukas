// Generates lib/settings/zone_countries.dart: the time zones the picker lists, each with its country,
// and the countries' names in Spanish and English.
//
// - The ids are ICU's spellings (`Intl.supportedValuesOf("timeZone")`: America/Buenos_Aires, Asia/Calcutta,
//   Europe/Kiev...), because those are what the web lists and what the API stores for a profile
//   (`canonicalTimeZone` in apps/api/src/auth.ts). A phone reports IANA's current spelling
//   (America/Argentina/Buenos_Aires), so the table also maps one to the other (`icuSpellings`).
// - The country of each zone is the tz database's zone.tab, kept in this folder (tool/zone.tab, tz 2026d)
//   so the result does not depend on the machine that runs this.
// - The names are CLDR's, through Node's Intl.DisplayNames.
//
// Pinned: Node 22 with ICU 78.2 (tz 2025c), the set `Intl.supportedValuesOf` has to equal (418 ids; the
// script stops if it does not). To update: bump the versions below and tool/zone.tab together, run
//
//   node tool/gen_zone_countries.mjs > lib/settings/zone_countries.dart && dart format lib/settings/zone_countries.dart
//
// and run `flutter test test/settings/settings_model_test.dart` (the ids must all be in the app's
// bundled database, timezone's `latest_all`).
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const PINNED = { icu: "78.2", tz: "2025c", zoneTab: "2026d", zones: 418 };

if (process.versions.icu !== PINNED.icu || process.versions.tz !== PINNED.tz) {
  console.error(
    `Needs ICU ${PINNED.icu} / tz ${PINNED.tz} (Node 22.22); this is ICU ${process.versions.icu} / tz ${process.versions.tz}.`,
  );
  process.exit(1);
}

const source = process.argv[2] ?? fileURLToPath(new URL("./zone.tab", import.meta.url));
const icuName = (zone) =>
  new Intl.DateTimeFormat(undefined, { timeZone: zone }).resolvedOptions().timeZone;
const rows = readFileSync(source, "utf8")
  .split("\n")
  .filter((line) => line && !line.startsWith("#"))
  .map((line) => line.split("\t"))
  .map(([country, , zone]) => ({ zone, id: icuName(zone), country }))
  .sort((a, b) => (a.id < b.id ? -1 : 1));

const supported = new Set(Intl.supportedValuesOf("timeZone"));
const ids = new Set(rows.map((row) => row.id));
const missing = [...supported].filter((id) => !ids.has(id));
const extra = [...ids].filter((id) => !supported.has(id));
if (rows.length !== PINNED.zones || missing.length || extra.length) {
  console.error(
    `The zones are not the web's: missing ${missing}, extra ${extra}, ${rows.length} rows`,
  );
  process.exit(1);
}

const codes = [...new Set(rows.map((row) => row.country))].sort();
const es = new Intl.DisplayNames(["es"], { type: "region" });
const en = new Intl.DisplayNames(["en"], { type: "region" });
const quote = (text) => `'${text.replaceAll("\\", "\\\\").replaceAll("'", "\\'")}'`;

const out = [];
out.push("// GENERATED by tool/gen_zone_countries.mjs: do not edit by hand.");
out.push(
  `// ${rows.length} zones, in ICU ${PINNED.icu}'s spelling (tz ${PINNED.tz}); countries from zone.tab (tz ${PINNED.zoneTab}); names from CLDR.`,
);
out.push("");
out.push("/// The country (ISO 3166 alpha-2) of each time zone the picker lists, by the web's id.");
out.push("const zoneCountries = <String, String>{");
for (const { id, country } of rows) out.push(`  ${quote(id)}: ${quote(country)},`);
out.push("};");
out.push("");
out.push(
  "/// IANA's current spelling of the zones ICU spells otherwise, to the web's: what a phone reports",
);
out.push("/// to what the web and the API store.");
out.push("const icuSpellings = <String, String>{");
for (const { zone, id } of rows
  .filter((row) => row.zone !== row.id)
  .sort((a, b) => (a.zone < b.zone ? -1 : 1))) {
  out.push(`  ${quote(zone)}: ${quote(id)},`);
}
out.push("};");
out.push("");
out.push("/// A country's name in Spanish and in English.");
out.push("const countryNames = <String, (String, String)>{");
for (const code of codes)
  out.push(`  ${quote(code)}: (${quote(es.of(code))}, ${quote(en.of(code))}),`);
out.push("};");
console.log(out.join("\n"));
