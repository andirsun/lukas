// ignore_for_file: file_names, avoid_print

/// Generates lib/theme/tokens.g.dart from the design system's tokens.json, the source the web's
/// tokens.css is generated from (apps/web/scripts/gen-tokens.ts).
///
/// Names follow the design system's, in lowerCamelCase: the colour `bg-glow` becomes
/// `LukitasTokens.night.bgGlow`, `space-4` becomes `LukitasTokens.space4`, `radius-sm` becomes
/// `LukitasTokens.radiusSm` and the duration `press` becomes `LukitasTokens.durationPress`. The
/// first theme in `color.themes` (night) is the default.
///
/// Usage, from apps/mobile: dart run scripts/gen-tokens.dart
/// CI regenerates the file and fails when the committed one differs.
library;

import 'dart:convert';
import 'dart:io';

/// tokens.json, relative to apps/mobile.
const tokensJsonPath = '../../docs/design/system/project/tokens.json';

/// The generated file, relative to apps/mobile.
const tokensDartPath = 'lib/theme/tokens.g.dart';

const _header =
    '''// Generated by scripts/gen-tokens.dart from docs/design/system/project/tokens.json.
// Do not edit: run `dart run scripts/gen-tokens.dart` and commit the result.
''';

String _camel(String name) {
  final parts = name.split('-');
  return parts.first +
      parts.skip(1).map((p) => p.isEmpty ? p : p[0].toUpperCase() + p.substring(1)).join();
}

String _capitalized(String name) => name[0].toUpperCase() + name.substring(1);

String _hex2(int value) => value.toRadixString(16).padLeft(2, '0').toUpperCase();

/// A CSS colour (`#rrggbb`, `#rgb` or `rgba(r, g, b, a)`) as a Dart `Color` literal.
String _color(String css, String where) {
  final value = css.trim();
  final hex = RegExp(r'^#([0-9a-fA-F]{3}|[0-9a-fA-F]{6})$').firstMatch(value);
  if (hex != null) {
    var digits = hex.group(1)!;
    if (digits.length == 3) digits = digits.split('').map((d) => '$d$d').join();
    return 'Color(0xFF${digits.toUpperCase()})';
  }
  final rgba = RegExp(r'^rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*(?:,\s*([0-9.]+)\s*)?\)$')
      .firstMatch(value);
  if (rgba != null) {
    final channels = [1, 2, 3].map((i) => int.parse(rgba.group(i)!)).toList();
    final alpha = rgba.group(4) == null ? 255 : (double.parse(rgba.group(4)!) * 255).round();
    if ([...channels, alpha].any((c) => c < 0 || c > 255)) {
      throw FormatException('$where: colour channel out of range in "$css"');
    }
    return 'Color(0x${_hex2(alpha)}${channels.map(_hex2).join()})';
  }
  throw FormatException('$where: unsupported colour "$css"');
}

/// A CSS length in px as a Dart double literal.
String _px(String css, String where) {
  final match = RegExp(r'^(\d+(?:\.\d+)?)px$').firstMatch(css.trim());
  if (match == null) throw FormatException('$where: expected a px length, got "$css"');
  final value = double.parse(match.group(1)!);
  return value == value.roundToDouble() ? '${value.round()}.0' : '$value';
}

/// A CSS duration (`80ms`, `1.2s`) as a Dart `Duration` literal.
String _duration(String css, String where) {
  final match = RegExp(r'^(\d+(?:\.\d+)?)(ms|s)$').firstMatch(css.trim());
  if (match == null) throw FormatException('$where: expected a duration, got "$css"');
  final amount = double.parse(match.group(1)!);
  final ms = match.group(2) == 's' ? amount * 1000 : amount;
  if (ms != ms.roundToDouble()) throw FormatException('$where: sub-millisecond duration "$css"');
  return 'Duration(milliseconds: ${ms.round()})';
}

String _doc(Object? usage, String indent) {
  if (usage is! String || usage.trim().isEmpty) return '';
  return '$indent/// ${usage.trim()}\n';
}

List<Map<String, dynamic>> _tokens(Map<String, dynamic> json, String group) =>
    ((json[group] as Map<String, dynamic>)['tokens'] as List).cast<Map<String, dynamic>>();

/// The Dart source of lib/theme/tokens.g.dart for a parsed tokens.json.
String generateTokensDart(Map<String, dynamic> json) {
  final color = json['color'] as Map<String, dynamic>;
  final themes = (color['themes'] as List)
      .cast<Map<String, dynamic>>()
      .map((t) => t['id'] as String)
      .toList();
  if (themes.isEmpty) throw const FormatException('tokens.json defines no colour themes');
  final colors = _tokens(json, 'color');

  final out = StringBuffer()
    ..writeln(_header)
    ..writeln("import 'package:flutter/painting.dart';")
    ..writeln()
    ..writeln('/// The colour tokens of one theme.')
    ..writeln('class LukitasColors {')
    ..writeln('  const LukitasColors({');
  for (final token in colors) {
    out.writeln('    required this.${_camel(token['name'] as String)},');
  }
  out
    ..writeln('  });')
    ..writeln();
  for (final token in colors) {
    out
      ..write(_doc(token['usage'], '  '))
      ..writeln('  final Color ${_camel(token['name'] as String)};')
      ..writeln();
  }
  for (final theme in themes) {
    out
      ..writeln('  static const $theme = LukitasColors(')
      ..writeAll(
        colors.map((token) {
          final name = token['name'] as String;
          final value = (token['value'] as Map<String, dynamic>)[theme];
          if (value is! String) {
            throw FormatException('Token "$name" has no value for theme "$theme"');
          }
          return '    ${_camel(name)}: ${_color(value, name)},\n';
        }),
      )
      ..writeln('  );');
  }
  out
    ..writeln('}')
    ..writeln()
    ..writeln('/// The design system tokens: colours per theme, spacing, radii and durations.')
    ..writeln('abstract final class LukitasTokens {')
    ..writeln('  /// The default theme.')
    ..writeln('  static const LukitasColors defaultTheme = LukitasColors.${themes.first};')
    ..writeln();
  for (final theme in themes) {
    out.writeln('  static const LukitasColors $theme = LukitasColors.$theme;');
  }

  for (final (group, title, prefix, literal) in [
    ('spacing', 'Spacing, in logical pixels.', '', _px),
    ('radius', 'Corner radii, in logical pixels.', '', _px),
    ('duration', 'Durations.', 'duration', _duration),
  ]) {
    out
      ..writeln()
      ..writeln('  // $title');
    final note = (json[group] as Map<String, dynamic>)['note'];
    if (note is String && note.trim().isNotEmpty) out.writeln('  // ${note.trim()}');
    for (final token in _tokens(json, group)) {
      final name = token['name'] as String;
      final dartName = prefix.isEmpty ? _camel(name) : '$prefix${_capitalized(_camel(name))}';
      out
        ..writeln()
        ..write(_doc(token['usage'], '  '))
        ..writeln('  static const $dartName = ${literal(token['value'] as String, name)};');
    }
  }
  out.writeln('}');
  return out.toString();
}

void main() {
  final tokens = jsonDecode(File(tokensJsonPath).readAsStringSync()) as Map<String, dynamic>;
  File(tokensDartPath).writeAsStringSync(generateTokensDart(tokens));
  print('Wrote $tokensDartPath');
}
