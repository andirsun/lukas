/**
 * Writes `app/api/schema.d.ts`, the TypeScript types of the API's OpenAPI document.
 *
 *   pnpm --filter @lukas/web api:types              fetches the document from a running API
 *   pnpm --filter @lukas/web api:types --file       builds it from the app in `apps/api`, no
 *                                                   server and no database (what CI does)
 *   pnpm --filter @lukas/web api:types --url <url>  fetches it from another address
 *
 * With `--document <absolute path>`, it writes the OpenAPI document itself there as JSON instead of
 * the types (the Android app's client generator, apps/mobile/scripts/gen-api.sh, reads it).
 *
 * The paths in the document carry no prefix (the API serves them under the pathname of its
 * API_URL, `/api`), so the web client sets `baseUrl: "/api"` and uses them as they are.
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import openapiTS, { astToString, type OpenAPI3 } from "openapi-typescript";

const OUTPUT = fileURLToPath(new URL("../app/api/schema.d.ts", import.meta.url));
const API_APP = fileURLToPath(new URL("../../api/src/app.ts", import.meta.url));

/** Where a dev API (`pnpm --filter @lukas/api dev`) serves its document, with or without /api. */
const DEFAULT_URLS = [
  "http://localhost:3000/openapi.json",
  "http://localhost:3000/api/openapi.json",
];

const HEADER = `/**
 * Generated by scripts/gen-api.ts from the API's OpenAPI document. Do not edit.
 * Regenerate with \`pnpm --filter @lukas/web api:types\`; CI fails when this file is stale.
 */

`;

interface ApiApp {
  request(path: string): Response | Promise<Response>;
}

/**
 * The real app factory with inert dependencies: building the app and reading /openapi.json touch
 * neither the database nor the mailer, so nothing connects and nothing is sent.
 */
async function documentFromApp(): Promise<OpenAPI3> {
  const { createApp } = (await import(pathToFileURL(API_APP).href)) as {
    createApp(deps: unknown): ApiApp;
  };
  const refuse = () => {
    throw new Error("gen-api builds the OpenAPI document only; it never connects to anything");
  };
  const app = createApp({
    config: {
      DATABASE_URL: "postgres://inert:inert@localhost:5432/inert",
      DATABASE_ADMIN_URL: "postgres://inert:inert@localhost:5432/inert",
      BETTER_AUTH_SECRET: "q7Hx2vK9mZpL4tRw8nYb3cDf6gJs1aEu",
      API_URL: "http://localhost:3000",
      WEB_URL: "http://localhost:5173",
      MAIL_FROM: "Lukitas <gen-api@lukas.test>",
      PORT: 3000,
      NODE_ENV: "test",
      CLIENT_IP_HEADER: "x-forwarded-for",
      GUEST_SIGNUP: true,
      TRUSTED_PROXIES: [],
    },
    db: new Proxy({}, { get: refuse }),
    mailer: { send: refuse },
  });
  const res = await app.request("/openapi.json");
  if (!res.ok) throw new Error(`The app answered ${res.status} for /openapi.json`);
  return (await res.json()) as OpenAPI3;
}

async function documentFromServer(urls: string[]): Promise<OpenAPI3> {
  const failures: string[] = [];
  for (const url of urls) {
    try {
      const res = await fetch(url);
      if (res.ok) return (await res.json()) as OpenAPI3;
      failures.push(`${url} answered ${res.status}`);
    } catch (error) {
      failures.push(`${url}: ${error instanceof Error ? error.message : String(error)}`);
    }
  }
  throw new Error(
    `Could not fetch the OpenAPI document (is the API running?)\n  ${failures.join("\n  ")}\nOr run with --file to build it from the app.`,
  );
}

const args = process.argv.slice(2);
const urlFlag = args.indexOf("--url");
const document = args.includes("--file")
  ? await documentFromApp()
  : await documentFromServer(
      urlFlag >= 0 && args[urlFlag + 1] ? [args[urlFlag + 1] as string] : DEFAULT_URLS,
    );

const documentFlag = args.indexOf("--document");
if (documentFlag >= 0) {
  const target = args[documentFlag + 1];
  if (!target) throw new Error("--document needs the path to write the OpenAPI document to");
  writeFileSync(target, `${JSON.stringify(document, null, 2)}\n`);
  console.log(`Wrote ${target}`);
} else {
  // A request field with a default is optional to send. The named request schemas live in
  // `components`, where openapi-typescript would otherwise make such fields required.
  const ast = await openapiTS(document, { defaultNonNullable: false });
  writeFileSync(OUTPUT, HEADER + astToString(ast));
  console.log(`Wrote ${OUTPUT}`);
}
