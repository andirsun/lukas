/**
 * Generates app/styles/tokens.css from the design system's tokens.json.
 *
 * Variable names are the design system's own (`--bg`, `--edge-sm`, `--press`, `--font-display`…),
 * so `lk-` component classes copied from bundle.css work unchanged. The first theme in
 * `color.themes` is the default: it applies on `:root` and on its own `[data-theme]` selector so
 * it can also be forced inside a subtree. Other themes override colors and shadows only.
 *
 * Usage: pnpm --filter @lukas/web tokens
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";

type Themed = Record<string, string>;

export interface TokensJson {
  color: {
    themes: { id: string; name: string }[];
    tokens: { name: string; value: Themed }[];
  };
  type: { families: Record<string, string> };
  spacing: { tokens: { name: string; value: string }[] };
  radius: { tokens: { name: string; value: string }[] };
  shadow: { tokens: { name: string; value: Themed }[] };
  duration: { tokens: { name: string; value: string }[] };
}

const HEADER =
  "/* Generated by scripts/gen-tokens.ts from docs/design/system/project/tokens.json. Do not edit. */";

function rule(selector: string, declarations: [string, string][]): string {
  const body = declarations.map(([name, value]) => `  --${name}: ${value};`).join("\n");
  return `${selector} {\n${body}\n}`;
}

function themedValue(token: { name: string; value: Themed }, theme: string): string {
  const value = token.value[theme];
  if (value === undefined) {
    throw new Error(`Token "${token.name}" has no value for theme "${theme}"`);
  }
  return value;
}

export function generateTokensCss(tokens: TokensJson): string {
  const themes = tokens.color.themes.map((t) => t.id);
  const [defaultTheme] = themes;
  if (defaultTheme === undefined) throw new Error("tokens.json defines no color themes");

  const themed = [...tokens.color.tokens, ...tokens.shadow.tokens];
  const themeRules = themes.map((theme) => {
    const selector =
      theme === defaultTheme ? `:root,\n[data-theme="${theme}"]` : `[data-theme="${theme}"]`;
    return rule(
      selector,
      themed.map((token) => [token.name, themedValue(token, theme)]),
    );
  });

  const constants: [string, string][] = [
    ...tokens.spacing.tokens.map((t): [string, string] => [t.name, t.value]),
    ...tokens.radius.tokens.map((t): [string, string] => [t.name, t.value]),
    ...tokens.duration.tokens.map((t): [string, string] => [t.name, t.value]),
    ...Object.entries(tokens.type.families).map(([name, value]): [string, string] => [
      `font-${name}`,
      value,
    ]),
  ];

  return `${[HEADER, ...themeRules, rule(":root", constants)].join("\n\n")}\n`;
}

function main(): void {
  const source = fileURLToPath(
    new URL("../../../docs/design/system/project/tokens.json", import.meta.url),
  );
  const target = fileURLToPath(new URL("../app/styles/tokens.css", import.meta.url));
  const tokens = JSON.parse(readFileSync(source, "utf8")) as TokensJson;
  writeFileSync(target, generateTokensCss(tokens));
  console.log(`Wrote ${target}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main();
}
